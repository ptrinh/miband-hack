const DICTS: Record<Lang, Record<Key, string>> = { en, zh, vi };

function detect(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'en' || saved === 'zh' || saved === 'vi') return saved;
  } catch {
    /* storage blocked or not in a browser */
  }
  const langs = typeof navigator !== 'undefined' ? navigator.languages ?? [navigator.language] : [];
  for (const l of langs) {
    const code = (l || '').toLowerCase();
    if (code.startsWith('zh')) return 'zh';
    if (code.startsWith('vi')) return 'vi';
    if (code.startsWith('en')) return 'en';
  }
  return 'en';
}

let current: Lang = detect();

export const getLang = (): Lang => current;

export function setLang(lang: Lang): void {
  current = lang;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    /* ignore */
  }
}

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s = DICTS[current][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** Picks the current language from a catalog field that is either a string or {en, zh, vi}. */
export function pick(v: string | Partial<Record<Lang, string>> | undefined): string {
  if (!v) return '';
  if (typeof v === 'string') return v;
  return v[current] ?? v.en ?? Object.values(v)[0] ?? '';
}

/** Applies data-i18n (text), data-i18n-html (trusted markup), data-i18n-alt/-title attributes. */
export function applyI18n(root: ParentNode = document): void {
  document.documentElement.lang = current === 'zh' ? 'zh-CN' : current;
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => (el.textContent = t(el.dataset.i18n as Key)));
  root.querySelectorAll<HTMLElement>('[data-i18n-html]').forEach((el) => (el.innerHTML = t(el.dataset.i18nHtml as Key)));
  root.querySelectorAll<HTMLElement>('[data-i18n-alt]').forEach((el) => el.setAttribute('alt', t(el.dataset.i18nAlt as Key)));
}
