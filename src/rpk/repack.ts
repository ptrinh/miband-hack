import { sha256 } from '@noble/hashes/sha2.js';
import { readZip, writeZip, type ZipEntry } from './zip';
import { bytesEqual, fileDigest, parseSignature, rsaVerify, signZip, spkiFromCertificate, toHex, toolkitNameCrc, zipDigest, type RpkSigner } from './sign';

/**
 * Re-packs an aiot-toolkit .rpk with some files replaced and signs it again, reproducing the
 * toolkit's pipeline (aiotpack ZipUtil.createRpk + SignUtil.signPackage):
 *
 *  - META-INF/CERT is itself a zip holding `hash.json` = {"algorithm":"SHA-256","digests":{path: hex}}
 *    for every file except META-INF/CERT (META-INF/build.txt included), signed with the same
 *    RPK Sig Block (file list = [{name:"hash.json", hash: SHA-256(unsigned CERT zip)}]).
 *  - The outer zip = [signed CERT, the other files in their original order] (directory entries kept),
 *    signed with file list = signed CERT + every non-directory file except META-INF/CERT.
 */

export const CERT_PATH = 'META-INF/CERT';
export const HASH_JSON = 'hash.json';

const utf8 = new TextEncoder();
const utf8d = new TextDecoder();

export interface RepackOptions {
  /** Timestamp written into the zip entries (default: now). */
  date?: Date;
}

function normalizePath(p: string): string {
  return p.replace(/^\/+/, '');
}

export async function repackRpk(
  original: Uint8Array,
  replace: Record<string, Uint8Array>,
  signer: RpkSigner,
  options: RepackOptions = {},
): Promise<Uint8Array> {
  const date = options.date ?? new Date();
  const src = readZip(original);
  const entries: ZipEntry[] = src.entries.map((e) => ({ name: e.name, data: e.data }));
  const index = new Map(entries.map((e, i) => [e.name, i]));
  if (!index.has('manifest.json')) throw new Error('rpk: manifest.json missing');

  for (const [rawPath, data] of Object.entries(replace)) {
    const path = normalizePath(rawPath);
    if (!path || path.endsWith('/') || path.includes('..')) throw new Error(`rpk: bad path ${rawPath}`);
    if (path.startsWith('META-INF/')) throw new Error(`rpk: ${path} is generated by the signer and cannot be replaced`);
    const i = index.get(path);
    if (i !== undefined) {
      entries[i] = { name: path, data };
      continue;
    }
    // New file: add missing parent folders (as JSZip does) and insert before META-INF/build.txt.
    const add: ZipEntry[] = [];
    const parts = path.split('/');
    for (let k = 1; k < parts.length; k++) {
      const dir = parts.slice(0, k).join('/') + '/';
      if (!index.has(dir) && !add.some((a) => a.name === dir)) add.push({ name: dir, data: new Uint8Array(0) });
    }
    add.push({ name: path, data });
    const buildTxt = entries.findIndex((e) => e.name === 'META-INF/build.txt');
    entries.splice(buildTxt >= 0 ? buildTxt : entries.length, 0, ...add);
    index.clear();
    entries.forEach((e, j) => index.set(e.name, j));
  }

  const isFile = (e: ZipEntry) => !e.name.endsWith('/');

  // 1. META-INF/CERT: zip { hash.json } with the original CERT's zip comment, then signed.
  const oldCert = entries.find((e) => e.name === CERT_PATH);
  const certComment = oldCert ? readZip(oldCert.data).comment : src.comment;
  // A bytecode build (--enable-jsc) lists each .jsc under its .js name with the digest of the JS source,
  // which we cannot recompute: carry those entries over from the original hash.json.
  const oldDigests = oldCert ? certDigests(oldCert.data) : {};
  // Keep the original key order (the toolkit's differs from the zip order for compiled scripts).
  const digests: Record<string, string> = {};
  const present = new Set(entries.flatMap((e) => [e.name, jsSourceName(e.name) ?? e.name]));
  for (const k of Object.keys(oldDigests)) if (present.has(k)) digests[k] = '';
  for (const e of entries) {
    if (!isFile(e) || e.name === CERT_PATH) continue;
    const js = jsSourceName(e.name);
    if (js && oldDigests[js] && !(e.name in replace)) digests[js] = oldDigests[js];
    else digests[e.name] = toHex(sha256(e.data));
  }
  for (const k of Object.keys(digests)) if (!digests[k]) delete digests[k];
  const hashJson = utf8.encode(JSON.stringify({ algorithm: 'SHA-256', digests }));
  const certZip = writeZip([{ name: HASH_JSON, data: hashJson }], certComment, date);
  const signedCert = await signZip(certZip, [fileDigest(HASH_JSON, certZip)], signer);

  // 2. Outer zip: CERT first (with its folder entry), then everything else in original order.
  const out: ZipEntry[] = [];
  out.push({ name: 'META-INF/', data: new Uint8Array(0) });
  out.push({ name: CERT_PATH, data: signedCert });
  for (const e of entries) if (e.name !== CERT_PATH && e.name !== 'META-INF/') out.push(e);

  const files = [fileDigest(CERT_PATH, signedCert)];
  for (const e of out) if (isFile(e) && e.name !== CERT_PATH) files.push(fileDigest(e.name, e.data));

  const unsigned = writeZip(out, src.comment, date);
  return signZip(unsigned, files, signer);
}

/** `app.jsc` → `app.js`, the name the toolkit's hash.json uses for compiled scripts. */
function jsSourceName(name: string): string | null {
  return name.endsWith('.jsc') ? name.slice(0, -1) : null;
}

function certDigests(cert: Uint8Array): Record<string, string> {
  const hj = readZip(cert).entries.find((e) => e.name === HASH_JSON);
  if (!hj) return {};
  return (JSON.parse(utf8d.decode(hj.data)) as { digests?: Record<string, string> }).digests ?? {};
}

// ---------- verification (re-implementation of what the toolkit writes) ----------

export interface RpkVerification {
  ok: boolean;
  errors: string[];
  /** SHA-256 of the signing certificate (DER), hex. */
  certificateSha256?: string;
}

async function verifySigned(label: string, signed: Uint8Array, errors: string[]) {
  const sig = parseSignature(signed);
  if (!sig) {
    errors.push(`${label}: no RPK signature block`);
    return null;
  }
  if (!bytesEqual(zipDigest(sig.unsignedZip), sig.signedDigest)) errors.push(`${label}: zip digest mismatch`);
  if (!bytesEqual(spkiFromCertificate(sig.certificateDer), sig.publicKeyDer)) errors.push(`${label}: public key does not match certificate`);
  if (!(await rsaVerify(sig.publicKeyDer, sig.signature, sig.signedData))) errors.push(`${label}: bad RSA signature`);
  if (!sig.fileData || !sig.fileSignature) errors.push(`${label}: no file digest block`);
  else if (!(await rsaVerify(sig.publicKeyDer, sig.fileSignature, sig.fileData))) errors.push(`${label}: bad file digest signature`);
  return sig;
}

/**
 * Verifies a signed rpk: outer signature + file digest block, META-INF/CERT signature and
 * hash.json digests. This mirrors the structure aiot-toolkit produces; the band's own verifier
 * is not public, so passing this does not prove the band will accept the package.
 */
export async function verifyRpk(rpk: Uint8Array): Promise<RpkVerification> {
  const errors: string[] = [];
  try {
    const outer = await verifySigned('rpk', rpk, errors);
    if (!outer) return { ok: false, errors };
    const zip = readZip(rpk);
    const files = zip.entries.filter((e) => !e.name.endsWith('/'));

    // file digest block must list every file with the right content hash
    const listed = outer.files.map((f) => `${f.nameCrc}:${toHex(f.hash)}`).sort();
    const actual = files.map((e) => `${toolkitNameCrc(e.name)}:${toHex(sha256(e.data))}`).sort();
    if (listed.join() !== actual.join()) errors.push('rpk: file digest block does not match the zip contents');

    const cert = files.find((e) => e.name === CERT_PATH);
    if (!cert) errors.push('rpk: META-INF/CERT missing');
    else {
      const inner = await verifySigned('CERT', cert.data, errors);
      if (inner) {
        if (inner.files.length !== 1 || inner.files[0].nameCrc !== toolkitNameCrc(HASH_JSON) || !bytesEqual(inner.files[0].hash, sha256(inner.unsignedZip))) {
          errors.push('CERT: file digest block is not hash.json of the unsigned CERT zip');
        }
        const hj = readZip(cert.data).entries.find((e) => e.name === HASH_JSON);
        if (!hj) errors.push('CERT: hash.json missing');
        else {
          const parsed = JSON.parse(utf8d.decode(hj.data)) as { algorithm?: string; digests?: Record<string, string> };
          if (parsed.algorithm !== 'SHA-256' || !parsed.digests) errors.push('CERT: unexpected hash.json');
          else {
            const want = files.filter((e) => e.name !== CERT_PATH);
            if (Object.keys(parsed.digests).length !== want.length) errors.push('CERT: hash.json file count mismatch');
            for (const e of want) {
              const js = jsSourceName(e.name);
              if (js && parsed.digests[js] && !(e.name in parsed.digests)) continue; // source digest, not checkable
              if (parsed.digests[e.name] !== toHex(sha256(e.data))) errors.push(`CERT: hash.json digest mismatch for ${e.name}`);
            }
          }
        }
        if (!bytesEqual(inner.certificateDer, outer.certificateDer)) errors.push('CERT and rpk are signed with different certificates');
      }
    }
    return { ok: errors.length === 0, errors, certificateSha256: toHex(sha256(outer.certificateDer)) };
  } catch (e) {
    errors.push(e instanceof Error ? e.message : String(e));
    return { ok: false, errors };
  }
}
